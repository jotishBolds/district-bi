const translations: Record<SamadhanLocale, TranslationDict> = { en, hi, ne };

// ─── PROVIDER ────────────────────────────────────────────────────────────────

export function SamadhanI18nProvider({
  children,
}: {
  children: React.ReactNode;
}) {
  const [locale, setLocaleState] = useState<SamadhanLocale>("en");

  // Load saved locale
  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as SamadhanLocale | null;
      if (saved && translations[saved]) {
        setLocaleState(saved);
      }
    } catch {}
  }, []);

  const setLocale = useCallback((newLocale: SamadhanLocale) => {
    setLocaleState(newLocale);
    try {
      localStorage.setItem(STORAGE_KEY, newLocale);
    } catch {}
  }, []);

  const t = useCallback(
    (key: string, replacements?: Record<string, string | number>): string => {
      let text = translations[locale]?.[key] || translations.en[key] || key;
      if (replacements) {
        Object.entries(replacements).forEach(([k, v]) => {
          text = text.replace(`{${k}}`, String(v));
        });
      }
      return text;
    },
    [locale],
  );

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
}

// ─── HOOK ────────────────────────────────────────────────────────────────────

export function useSamadhanI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useSamadhanI18n must be used within SamadhanI18nProvider");
  }
  return context;
}
